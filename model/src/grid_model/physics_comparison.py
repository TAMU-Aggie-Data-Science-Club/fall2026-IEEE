"""Model-generated transformer consistency experiments, never measured truth."""
from dataclasses import asdict
import json
from pathlib import Path
import time
import numpy as np
import joblib
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import Ridge
from .physics_ieee import TransformerParameters, run_profile as ieee
from .physics_alliander import run_profile as iec
from .crossing import detection_metrics, first_crossing


def comparison(output, parameters=None):
    p = parameters or TransformerParameters()
    traces = []
    for index in range(18):
        split = "train" if index < 10 else "val" if index < 14 else "test"
        times = np.arange(0, 3601, 30)
        # Explicit known forcing for truth; forecasts hold only last known load.
        load = np.full(len(times), .55+.02*(index % 4))
        load[times >= 600] = 1.1+.11*(index % 5)
        load[times >= 2100] = .75 if index % 2 else 1.55
        ambient = np.full(len(times), 22.+(index % 5)*4)
        for truth_name, runner in (("ieee_generated", ieee), ("iec_generated", iec)):
            truth = runner(times, load, ambient, p)
            for origin in range(10, 101, 2):
                hot, oil = truth["hotspot_c"][origin], truth["top_oil_c"][origin]
                row = dict(split=split, scenario=f"T{index:02d}", truth=truth_name,
                           x=[hot, oil, load[origin], ambient[origin], hot-truth["hotspot_c"][origin-2]],
                           y=[truth["hotspot_c"][origin+2], truth["hotspot_c"][origin+10]],
                           current=hot)
                truth_segment = truth["hotspot_c"][origin:origin+11]
                row["eta"] = first_crossing(np.arange(0,301,30), truth_segment, p.threshold_c)
                row["label"] = row["eta"] is not None
                if split != "train":
                    forecast_times = np.r_[times[:origin+1], times[origin]+np.arange(30,301,30)]
                    forecast_load = np.r_[load[:origin+1], np.full(10,load[origin])]
                    forecast_ambient = np.r_[ambient[:origin+1], np.full(10,ambient[origin])]
                    row["predictions"], row["runtime_ms"], row["predicted_eta"] = {}, {}, {}
                    for name, predict in (("ieee_c57_91", ieee), ("alliander_iec", iec)):
                        start = time.perf_counter()
                        forecast = predict(forecast_times, forecast_load, forecast_ambient, p)
                        row["runtime_ms"][name] = (time.perf_counter()-start)*1000
                        row["predictions"][name] = [forecast["hotspot_c"][origin+2], forecast["hotspot_c"][-1]]
                        row["predicted_eta"][name] = first_crossing(np.arange(0,301,30),forecast["hotspot_c"][origin:origin+11],p.threshold_c)
                traces.append(row)
    training = [row for row in traces if row["split"] == "train"]
    validation = [row for row in traces if row["split"] == "val"]
    candidates = []
    for alpha in (.1, 1., 10.):
        model = make_pipeline(StandardScaler(), Ridge(alpha=alpha)).fit([r["x"] for r in training], [r["y"] for r in training])
        loss = np.abs(model.predict([r["x"] for r in validation])-np.asarray([r["y"] for r in validation])).mean()
        candidates.append((loss, alpha, model))
    _, alpha, ridge = min(candidates, key=lambda x:x[0])
    result = dict(provenance="new synthetic oil-transformer scenarios generated separately by IEEE and IEC; consistency/disagreement, NOT physical accuracy",
                  original_rc_ridge="retained unchanged; invalid domain for transformer amperes/insulation; not relabeled or evaluated as a transformer",
                  transformer_ridge="separate Ridge surrogate fit ONLY on train transformer scenarios generated by both models",
                  parameters=asdict(p), ridge_alpha=alpha, scenario_splits=dict(train=10,val=4,test=4), test={})
    for truth_name in ("ieee_generated", "iec_generated"):
        rows = [r for r in traces if r["split"] == "test" and r["truth"] == truth_name]
        truth = np.asarray([r["y"] for r in rows])
        result["test"][truth_name] = {}
        for name in ("ieee_c57_91", "alliander_iec", "ridge_transformer"):
            start = time.perf_counter()
            pred = ridge.predict([r["x"] for r in rows]) if name == "ridge_transformer" else np.asarray([r["predictions"][name] for r in rows])
            latency = (time.perf_counter()-start)*1000/len(rows) if name == "ridge_transformer" else float(np.mean([r["runtime_ms"][name] for r in rows]))
            delta = pred-truth
            result["test"][truth_name][name] = dict(horizons={str(h):dict(mae_c=float(np.abs(delta[:,i]).mean()),rmse_c=float(np.sqrt((delta[:,i]**2).mean()))) for i,h in enumerate((60,300))},
                detection=detection_metrics([r["current"] for r in rows], pred, [r["label"] for r in rows],
                    [r["eta"] if r["eta"] is not None else -1 for r in rows], threshold=p.threshold_c,
                    predicted_eta=None if name == "ridge_transformer" else [r["predicted_eta"][name] for r in rows]),
                cpu_ms_per_forecast=latency, count=len(rows))
    out = Path(output); out.mkdir(parents=True, exist_ok=True)
    joblib.dump(ridge, out/"transformer-ridge.joblib")
    (out/"comparison.json").write_text(json.dumps(result,indent=2,allow_nan=False),encoding="utf-8")
    return result
